// listExpr returns a Go expression of type []lg.Value holding all values of
// exprs, with the last expression expanded when it is multi-valued.
func (f *fnGen) listExpr(exprs []ast.Expr) string {
	if len(exprs) == 0 {
		return "nil"
	}
	last := exprs[len(exprs)-1]
	if !isMulti(last) || f.isDirectCall(last) {
		parts := make([]string, len(exprs))
		for i, e := range exprs {
			parts[i] = f.expr(e)
		}
		return "[]lg.Value{" + strings.Join(parts, ", ") + "}"
	}
	if len(exprs) == 1 {
		switch lv := last.(type) {
		case *ast.CallExpr:
			if src, ok := f.directCallSrc(lv); ok {
				return "[]lg.Value{" + src + "}"
			}
			r := f.temp("r")
			fn := f.calleeSrc(lv)
			args := f.callArgs(lv.Args, "")
			f.line("%s := lg.Call(env, %s, %s)", r, fn, args)
			return r
		case *ast.MethodExpr:
			r := f.temp("r")
			recv := f.temp("recv")
			f.line("%s := %s", recv, f.expr(lv.Obj))
			args := f.callArgs(lv.Args, recv)
			f.line("%s := lg.Call(env, lg.Index(env, %s, lg.String(%s)), %s)",
				r, recv, strconv.Quote(lv.Name), args)
			return r
		case *ast.VarargExpr:
			return f.va
		}
	}
	r := f.temp("r")
	parts := make([]string, 0, len(exprs)-1)
	for _, e := range exprs[:len(exprs)-1] {
		parts = append(parts, f.expr(e))
	}
	f.line("%s := []lg.Value{%s}", r, strings.Join(parts, ", "))
	switch lv := last.(type) {
	case *ast.CallExpr:
		if src, ok := f.directCallSrc(lv); ok {
			f.line("%s = append(%s, %s)", r, r, src)
			return r
		}
		fn := f.calleeSrc(lv)
		args := f.callArgs(lv.Args, "")
		f.line("%s = append(%s, lg.Call(env, %s, %s)...)", r, r, fn, args)
	case *ast.MethodExpr:
		recv := f.temp("recv")
		f.line("%s := %s", recv, f.expr(lv.Obj))
		args := f.callArgs(lv.Args, recv)
		f.line("%s = append(%s, lg.Call(env, lg.Index(env, %s, lg.String(%s)), %s)...)",
			r, r, recv, strconv.Quote(lv.Name), args)
	case *ast.VarargExpr:
		f.line("%s = append(%s, %s...)", r, r, f.va)
	}
	return r
}

// evalExplist returns n Go expressions producing the values of exprs
// adjusted to exactly n values (Lua's assignment adjustment rules).
func (f *fnGen) evalExplist(exprs []ast.Expr, n int) []string {
	out := make([]string, n)
	if len(exprs) == 0 {
		for i := range out {
			out[i] = "lg.Nil"
		}
		return out
	}
	// Fast path: one expression, one wanted value.
	if n == 1 && len(exprs) == 1 && isMulti(exprs[0]) && !f.isDirectCall(exprs[0]) {
		switch lv := exprs[0].(type) {
		case *ast.CallExpr:
			fn := f.calleeSrc(lv)
			args := f.callArgs(lv.Args, "")
			out[0] = fmt.Sprintf("lg.Call1(env, %s, %s)", fn, args)
			return out
		case *ast.MethodExpr:
			recv := f.temp("recv")
			f.line("%s := %s", recv, f.expr(lv.Obj))
			args := f.callArgs(lv.Args, recv)
			out[0] = fmt.Sprintf("lg.Call1(env, lg.Index(env, %s, lg.String(%s)), %s)",
				recv, strconv.Quote(lv.Name), args)
			return out
		case *ast.VarargExpr:
			out[0] = fmt.Sprintf("lg.Pick(%s, 0)", f.va)
			return out
		}
	}
	last := exprs[len(exprs)-1]
	if !isMulti(last) || f.isDirectCall(last) {
		for i := range out {
			out[i] = "lg.Nil"
		}
		for i, e := range exprs {
			if i < n {
				out[i] = f.expr(e)
			}
		}
		return out
	}
	r := f.listExpr(exprs)
	for i := 0; i < n; i++ {
		out[i] = fmt.Sprintf("lg.Pick(%s, %d)", r, i)
	}
	return out
}

// callArgs returns a Go expression of type []lg.Value for a call's
// arguments; prepend is the receiver for method calls.
func (f *fnGen) callArgs(args []ast.Expr, prepend string) string {
	if len(args) == 0 {
		if prepend == "" {
			return "nil"
		}
		return "[]lg.Value{" + prepend + "}"
	}
	last := args[len(args)-1]
	if !isMulti(last) || f.isDirectCall(last) {
		parts := make([]string, 0, len(args)+1)
		if prepend != "" {
			parts = append(parts, prepend)
		}
		for _, a := range args {
			parts = append(parts, f.expr(a))
		}
		return "[]lg.Value{" + strings.Join(parts, ", ") + "}"
	}
	av := f.temp("av")
	if prepend == "" {
		f.line("%s := make([]lg.Value, 0, %d)", av, len(args))
	} else {
		f.line("%s := []lg.Value{%s}", av, prepend)
	}
	for _, a := range args[:len(args)-1] {
		f.line("%s = append(%s, %s)", av, av, f.expr(a))
	}
	switch lv := last.(type) {
	case *ast.CallExpr:
		if src, ok := f.directCallSrc(lv); ok {
			f.line("%s = append(%s, %s)", av, av, src)
			return av
		}
		fn := f.calleeSrc(lv)
		cargs := f.callArgs(lv.Args, "")
		f.line("%s = append(%s, lg.Call(env, %s, %s)...)", av, av, fn, cargs)
	case *ast.MethodExpr:
		recv := f.temp("recv")
		f.line("%s := %s", recv, f.expr(lv.Obj))
		cargs := f.callArgs(lv.Args, recv)
		f.line("%s = append(%s, lg.Call(env, lg.Index(env, %s, lg.String(%s)), %s)...)",
			av, av, recv, strconv.Quote(lv.Name), cargs)
	case *ast.VarargExpr:
		f.line("%s = append(%s, %s...)", av, av, f.va)
	}
	return av
}

// Package codegen translates a Lua AST into Go source code.
//
// Translation model:
//
//   - Every Lua function (including the chunk) becomes a Go func literal
//     with the uniform signature func(env *lg.Env, args []lg.Value) []lg.Value,
//     wrapped by lg.NewClosure. Closures capture Go variables directly, so
//     Lua upvalue sharing falls out of Go's own closure semantics.
//   - Every Lua local becomes a Go variable of type lg.Value with a unique
//     name (name_N). Unique renaming makes shadowing, closure conversion and
//     goto-hoisting all trivially correct.
//   - Lua's multiple-value rule is implemented by materializing []lg.Value
//     slices (lg.Call / append) exactly where Lua adjusts value lists.
//   - Runtime operations are calls into package runtime (lg.Arith, lg.Index,
//     ...); the type specialization pass that turns monomorphic number locals
//     into plain float64 locals is a future optimization and is not required
//     for correctness.
package codegen

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"github.com/pulseaiclub/lug/internal/ast"
)

// Options configures Generate.
type Options struct {
	// Package is the Go package name of the generated file (default "main").
	Package string
	// ChunkName is the Go identifier for the generated chunk var
	// (default "Chunk_main").
	ChunkName string
	// Source is the original .lua path, used in comments.
	Source string
}

const runtimeImport = "github.com/pulseaiclub/lug/runtime"

// Generate transpiles a parsed chunk into formatted Go source.
//
// It runs two passes: the first collects how every local function is used
// (direct calls vs. used as a value); the second emits fixed-arity Go
// functions for the ones that are only ever called directly, which removes
// the per-call argument slice allocation.
func Generate(file *ast.File, opts Options) ([]byte, error) {
	if opts.Package == "" {
		opts.Package = "main"
	}
	if opts.ChunkName == "" {
		opts.ChunkName = "Chunk_main"
	}

	// Pass 1: usage collection and numeric type inference, iterated to a
	// fixpoint (the state only ever grows, so it converges quickly).
	var num *numInfo
	var qualified map[string]*directInfo
	for i := 0; i < 16; i++ {
		g := &gen{opts: opts, collecting: true, num: num,
			usage: map[string]*usageInfo{}, localFuncs: map[string]*ast.LocalFuncStmt{},
			noNum: map[string]bool{}, loopVars: map[string]bool{},
			fnParams: map[string][]string{}, fnParamNum: map[string]bool{},
			fnRetNum: map[string]bool{}, fnRetSeen: map[string]bool{}}
		if qualified != nil {
			g.direct = qualified
		}
		g.emitChunk(file)
		if qualified == nil {
			qualified = g.qualify()
		}
		next := g.computeNum()
		stable := sameNum(num, next)
		num = next
		// Two extra rounds after the first: direct-call specialization is
		// only known after the first pass, and it feeds the numeric analysis.
		if stable && i >= 2 {
			break
		}
	}

	// Pass 2: final emission with direct-call and numeric specialization.
	g2 := &gen{opts: opts, direct: qualified, num: num}
	f := g2.emitChunk(file)

	var sb strings.Builder
	fmt.Fprintf(&sb, "// Code generated by lug from %s. DO NOT EDIT.\n\n", opts.Source)
	fmt.Fprintf(&sb, "package %s\n\n", opts.Package)
	fmt.Fprintf(&sb, "import lg %q\n\n", runtimeImport)
	sb.WriteString("var _ = lg.Nil\n\n")
	fmt.Fprintf(&sb, "// %s is the entry point transpiled from %s.\n", opts.ChunkName, opts.Source)
	fmt.Fprintf(&sb, "var %s lg.Fn = func(env *lg.Env, args []lg.Value) []lg.Value {\n%s\n}\n",
		opts.ChunkName, strings.Join(f.buf, "\n"))

	src := sb.String()
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("lug: generated Go failed to format: %w\n--- generated source ---\n%s", err, src)
	}
	return out, nil
}

// endsWithReturn reports whether a block's last statement returns, which
// makes a trailing fallback return unreachable (and unwelcome to go vet).
func endsWithReturn(b *ast.Block) bool {
	if len(b.Stmts) == 0 {
		return false
	}
	_, ok := b.Stmts[len(b.Stmts)-1].(*ast.ReturnStmt)
	return ok
}

// emitChunk generates the main chunk function and returns its emitter.
func (g *gen) emitChunk(file *ast.File) *fnGen {
	g.pushScope()
	f := &fnGen{g: g, labelGo: map[string]string{}, labels: collectGotos(&ast.Block{Stmts: file.Stmts})}
	f.ind = 1
	f.va = g.declare("va")
	f.line("%s := lg.Tail(args, 0)", f.va)
	f.line("_ = %s", f.va)
	body := &ast.Block{Stmts: file.Stmts}
	f.emitBlock(body)
	if !endsWithReturn(body) {
		f.line("return nil")
	}
	g.popScope()
	return f
}

// ---------------------------------------------------------------------------
// Numeric type inference
// ---------------------------------------------------------------------------

// isNumExpr reports whether e is statically known to evaluate to a number
// under the current inference state. It never emits code.
func (f *fnGen) isNumExpr(e ast.Expr) bool {
	switch v := e.(type) {
	case *ast.NumberExpr:
		return true
	case *ast.UnExpr:
		return v.Op == ast.UnNeg && f.isNumExpr(v.X)
	case *ast.BinExpr:
		switch v.Op {
		case ast.OpAdd, ast.OpSub, ast.OpMul, ast.OpDiv, ast.OpMod, ast.OpPow, ast.OpIDiv:
			return f.isNumExpr(v.L) && f.isNumExpr(v.R)
		}
		return false
	case *ast.NameExpr:
		gn, ok := f.g.resolve(v.Name)
		if !ok {
			return false
		}
		// Optimistic seeds for the fixpoint: a local is assumed numeric while
		// its own assignments are checked, and the parameters of the function
		// being analyzed are assumed numeric (which is exactly what makes it
		// typed). Any disagreeing fact removes the local again.
		return f.g.isNumLocal(gn) || gn == f.curLocal || f.g.isParamOf(f.fnGN, gn)
	case *ast.CallExpr:
		nm, ok := v.Fn.(*ast.NameExpr)
		if !ok {
			return false
		}
		// Specialized functions are not in the value scope, so the callee is
		// resolved through the direct-call table.
		di, ok := f.g.resolveDirect(nm.Name)
		if !ok || len(v.Args) != di.arity {
			return false
		}
		// A call to the function currently being analyzed is assumed to
		// return a number: the fixpoint rejects it if that is untrue.
		return f.g.numRetNum(di.goName) || di.goName == f.fnGN
	}
	return false
}

// isParamOf reports whether gn is one of the parameters of the direct
// function fn.
func (g *gen) isParamOf(fn, gn string) bool {
	if fn == "" {
		return false
	}
	for _, p := range g.fnParams[fn] {
		if p == gn {
			return true
		}
	}
	return false
}

func (g *gen) isNumLocal(gn string) bool {
	if g.num == nil {
		return false
	}
	return g.num.locals[gn]
}

func (g *gen) numRetNum(gn string) bool {
	if g.num == nil {
		return false
	}
	return g.num.rets[gn]
}

// numFunc reports whether a direct function is emitted with float64
// parameters and a float64 result.
func (g *gen) numFunc(gn string) bool {
	if g.num == nil {
		return false
	}
	return g.num.params[gn] && g.num.rets[gn]
}

// markLoopVar records that gn is a numeric for-loop control variable.
func (g *gen) markLoopVar(gn string) {
	if g.loopVars == nil {
		g.loopVars = map[string]bool{}
	}
	g.loopVars[gn] = true
}

// markNoNum excludes gn from numeric specialization.
func (g *gen) markNoNum(gn string) {
	if g.noNum == nil {
		g.noNum = map[string]bool{}
	}
	g.noNum[gn] = true
}

func (g *gen) markDeclInit(gn string) {
	if !g.collecting {
		return
	}
	if g.assigns == nil {
		g.assigns = map[string]*assignInfo{}
	}
	a := g.assigns[gn]
	if a == nil {
		a = &assignInfo{allNum: true}
		g.assigns[gn] = a
	}
	a.declInit = true
}

// adjustedExprs maps an expression list onto n assignment targets following
// Lua's adjustment rules, using nil for positions whose value is unknown or
// comes from a multi-value expansion.
func (f *fnGen) adjustedExprs(vals []ast.Expr, n int) []ast.Expr {
	out := make([]ast.Expr, n)
	if len(vals) == 0 {
		return out
	}
	last := vals[len(vals)-1]
	multi := isMulti(last) && !f.isDirectCall(last)
	for i := 0; i < n; i++ {
		if i < len(vals)-1 {
			out[i] = vals[i]
			continue
		}
		if i == len(vals)-1 && !multi {
			out[i] = last
		}
	}
	return out
}

func (g *gen) recordAssign(gn string, num bool) {
	if !g.collecting {
		return
	}
	if g.assigns == nil {
		g.assigns = map[string]*assignInfo{}
	}
	a := g.assigns[gn]
	if a == nil {
		a = &assignInfo{allNum: true}
		g.assigns[gn] = a
	}
	a.seen = true
	if !num {
		a.allNum = false
	}
}

// computeNum derives the next inference state from this iteration's facts.
func (g *gen) computeNum() *numInfo {
	out := &numInfo{locals: map[string]bool{}, params: map[string]bool{}, rets: map[string]bool{}}
	for gn, a := range g.assigns {
		if a.declInit && a.allNum && a.seen && !g.noNum[gn] {
			out.locals[gn] = true
		}
	}
	for gn := range g.loopVars {
		out.locals[gn] = true
	}
	for gn, ok := range g.fnParamNum {
		if ok {
			out.params[gn] = true
		}
	}
	for gn, ok := range g.fnRetNum {
		if ok && g.fnRetSeen[gn] {
			out.rets[gn] = true
		}
	}
	// Parameters of fully typed functions are float64 locals too, so their
	// uses inside the body type-check as numbers.
	for gn := range out.params {
		if !out.rets[gn] {
			continue
		}
		for _, pgn := range g.fnParams[gn] {
			out.locals[pgn] = true
		}
	}
	return out
}

func sameNum(a, b *numInfo) bool {
	if a == nil {
		return len(b.locals) == 0 && len(b.params) == 0 && len(b.rets) == 0
	}
	eq := func(x, y map[string]bool) bool {
		if len(x) != len(y) {
			return false
		}
		for k := range x {
			if !y[k] {
				return false
			}
		}
		return true
	}
	return eq(a.locals, b.locals) && eq(a.params, b.params) && eq(a.rets, b.rets)
}

// ---------------------------------------------------------------------------
// Naming and scopes
// ---------------------------------------------------------------------------

type gen struct {
	opts    Options
	scopes  []map[string]string // Lua name -> Go name
	counter int

	// Pass 1: usage collection for direct-call specialization.
	collecting bool
	usage      map[string]*usageInfo
	localFuncs map[string]*ast.LocalFuncStmt

	// Pass 2: the qualified set (Go name -> info) and its scope chain.
	direct       map[string]*directInfo
	directScopes []map[string]*directInfo

	// Numeric type inference. num holds the state produced by the previous
	// analysis iteration, the *Record maps collect this iteration's facts.
	num        *numInfo
	assigns    map[string]*assignInfo
	loopVars   map[string]bool
	noNum      map[string]bool
	fnParams   map[string][]string
	fnParamNum map[string]bool
	fnRetNum   map[string]bool
	fnRetSeen  map[string]bool
}

// numInfo is the numeric-type inference state: which locals are Go float64
// variables, which direct functions take float64 parameters, and which
// return a float64.
type numInfo struct {
	locals map[string]bool
	params map[string]bool
	rets   map[string]bool
}

// assignInfo records the assignments to one local.
type assignInfo struct {
	declInit bool // the declaration provided an initializer
	allNum   bool // every recorded assignment was a numeric expression
	seen     bool
}

// usageInfo tracks how a resolved local is referenced.
type usageInfo struct {
	calls, other int
	arities      []int
	multiLast    bool
}

// directInfo describes a local function emitted as a fixed-arity Go func.
type directInfo struct {
	goName string
	arity  int
}

func (g *gen) pushScope() {
	g.scopes = append(g.scopes, map[string]string{})
	g.directScopes = append(g.directScopes, map[string]*directInfo{})
}

func (g *gen) popScope() {
	g.scopes = g.scopes[:len(g.scopes)-1]
	g.directScopes = g.directScopes[:len(g.directScopes)-1]
}

func (g *gen) usageFor(gn string) *usageInfo {
	u := g.usage[gn]
	if u == nil {
		u = &usageInfo{}
		g.usage[gn] = u
	}
	return u
}

// declareDirect registers a direct-callable function name in the current scope.
func (g *gen) declareDirect(name string, di *directInfo) {
	g.directScopes[len(g.directScopes)-1][name] = di
}

// resolveDirect finds a direct-callable function by Lua name.
func (g *gen) resolveDirect(name string) (*directInfo, bool) {
	for i := len(g.directScopes) - 1; i >= 0; i-- {
		if di, ok := g.directScopes[i][name]; ok {
			return di, true
		}
	}
	return nil, false
}

// qualify decides which collected local functions can be emitted as
// fixed-arity Go funcs: only ever called directly, always with the exact
// arity, never with a multi-value last argument, and every return yields
// exactly one value.
func (g *gen) qualify() map[string]*directInfo {
	out := map[string]*directInfo{}
	for gn, u := range g.usage {
		if u.other > 0 || u.calls == 0 || u.multiLast {
			continue
		}
		stmt := g.localFuncs[gn]
		if stmt == nil || stmt.Vararg {
			continue
		}
		arityOK := true
		for _, a := range u.arities {
			if a != len(stmt.Params) {
				arityOK = false
				break
			}
		}
		if !arityOK || !allReturnsSingle(stmt.Body) {
			continue
		}
		out[gn] = &directInfo{goName: gn, arity: len(stmt.Params)}
	}
	return out
}

// allReturnsSingle reports whether every return statement of a function
// body returns exactly one non-multi value.
func allReturnsSingle(b *ast.Block) bool {
	ok := true
	var walk func(stmts []ast.Stmt)
	walk = func(stmts []ast.Stmt) {
		for _, s := range stmts {
			switch v := s.(type) {
			case *ast.ReturnStmt:
				if len(v.Vals) != 1 || isMulti(v.Vals[0]) {
					ok = false
				}
			case *ast.DoStmt:
				walk(v.Body.Stmts)
			case *ast.WhileStmt:
				walk(v.Body.Stmts)
			case *ast.RepeatStmt:
				walk(v.Body.Stmts)
			case *ast.IfStmt:
				for _, blk := range v.Blocks {
					walk(blk.Stmts)
				}
				if v.Else != nil {
					walk(v.Else.Stmts)
				}
			case *ast.NumForStmt:
				walk(v.Body.Stmts)
			case *ast.GenForStmt:
				walk(v.Body.Stmts)
			}
		}
	}
	walk(b.Stmts)
	return ok
}

// reserve allocates a unique Go name without binding it in scope.
func (g *gen) reserve(name string) string {
	g.counter++
	return sanitize(name) + "_" + strconv.Itoa(g.counter)
}

// declare allocates a unique Go name and binds the Lua name to it in the
// current scope.
func (g *gen) declare(name string) string {
	gn := g.reserve(name)
	g.scopes[len(g.scopes)-1][name] = gn
	return gn
}

// bind maps a Lua name to an already allocated Go name.
func (g *gen) bind(luaName, goName string) {
	g.scopes[len(g.scopes)-1][luaName] = goName
}

// resolve finds the Go name for a Lua identifier across the scope chain.
func (g *gen) resolve(name string) (string, bool) {
	for i := len(g.scopes) - 1; i >= 0; i-- {
		if gn, ok := g.scopes[i][name]; ok {
			return gn, true
		}
	}
	return "", false
}

// sanitize maps a Lua identifier to a safe Go identifier base.
func sanitize(name string) string {
	if name == "" {
		return "_"
	}
	var b strings.Builder
	for i, r := range name {
		switch {
		case r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z'):
			b.WriteRune(r)
		case r >= '0' && r <= '9':
			if i == 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	return b.String()
}

// ---------------------------------------------------------------------------
// Per-function emission state
// ---------------------------------------------------------------------------

type fnGen struct {
	g            *gen
	ind          int
	buf          []string
	tmp          int
	va           string            // vararg slice name ("" when not vararg)
	direct       bool              // this function returns a single lg.Value
	numFn        bool              // this function is emitted with float64 in/out
	fnGN         string            // Go name of the node function being emitted
	curLocal     string            // local whose assignment is being checked
	labels       map[string]bool   // goto-targeted label names in this function
	labelGo      map[string]string // Lua label -> Go label
	pendingLabel bool              // last emitted line is a bare label
	hoist        map[ast.Stmt][]string
}

func (f *fnGen) line(format string, args ...any) {
	f.buf = append(f.buf, strings.Repeat("\t", f.ind)+fmt.Sprintf(format, args...))
}

func (f *fnGen) temp(prefix string) string {
	f.tmp++
	return fmt.Sprintf("%s%d", prefix, f.tmp)
}

func (f *fnGen) labelGoName(name string) string {
	if gn, ok := f.labelGo[name]; ok {
		return gn
	}
	gn := fmt.Sprintf("L_%s_%d", sanitize(name), len(f.labelGo))
	f.labelGo[name] = gn
	return gn
}

// closure emits a NewClosure(...) expression for a Lua function.
func (g *gen) closure(params []string, vararg bool, name string, body *ast.Block) string {
	return fmt.Sprintf("lg.NewClosure(%s, %s)", g.funcLit(params, vararg, body), strconv.Quote(name))
}

// funcLit emits the raw Go func literal for a Lua function.
func (g *gen) funcLit(params []string, vararg bool, body *ast.Block) string {
	f := &fnGen{g: g, labelGo: map[string]string{}, labels: collectGotos(body)}
	g.pushScope()
	f.ind = 1
	for i, p := range params {
		pn := g.declare(p)
		f.line("var %s lg.Value = lg.Arg(args, %d)", pn, i)
		f.line("_ = %s", pn)
	}
	if vararg {
		f.va = g.declare("va")
		f.line("%s := lg.Tail(args, %d)", f.va, len(params))
		f.line("_ = %s", f.va)
	}
	f.emitBlock(body)
	if !endsWithReturn(body) {
		f.line("return nil")
	}
	g.popScope()
	return fmt.Sprintf("func(env *lg.Env, args []lg.Value) []lg.Value {\n%s\n}", strings.Join(f.buf, "\n"))
}

// ---------------------------------------------------------------------------
// Blocks
// ---------------------------------------------------------------------------

func blockHasTargetedLabel(b *ast.Block, labels map[string]bool) bool {
	for _, s := range b.Stmts {
		if ls, ok := s.(*ast.LabelStmt); ok && labels[ls.Name] {
			return true
		}
	}
	return false
}

// blockOpen pushes the block's scope and, when the block contains a
// targeted label, hoists all local declarations of the block to its top so
// that gotos never jump over a declaration (illegal in Go, fine in Lua
// because the label sits at the block end in the usual `::continue::` idiom).
func (f *fnGen) blockOpen(b *ast.Block) {
	f.g.pushScope()
	f.hoist = nil
	if !blockHasTargetedLabel(b, f.labels) {
		return
	}
	f.hoist = make(map[ast.Stmt][]string)
	for _, s := range b.Stmts {
		switch st := s.(type) {
		case *ast.LocalStmt:
			names := make([]string, len(st.Names))
			for i, n := range st.Names {
				gn := f.g.reserve(n)
				names[i] = gn
				f.line("var %s lg.Value", gn)
				f.line("_ = %s", gn)
			}
			f.hoist[s] = names
		case *ast.LocalFuncStmt:
			gn := f.g.reserve(st.Name)
			f.line("var %s lg.Value", gn)
			f.line("_ = %s", gn)
			f.hoist[s] = []string{gn}
		}
	}
}

func (f *fnGen) blockClose() {
	if f.pendingLabel {
		// A Go label must be followed by a statement; Lua's `::continue::`
		// idiom puts it right before the closing brace.
		f.line("_ = 0")
		f.pendingLabel = false
	}
	f.g.popScope()
}

func (f *fnGen) emitBlock(b *ast.Block) {
	f.emitBlockWithTail(b, nil)
}

// emitBlockWithTail emits a block plus a tail statement inside its scope
// (repeat-until needs the condition inside the body scope).
func (f *fnGen) emitBlockWithTail(b *ast.Block, tail func()) {
	savedHoist := f.hoist
	f.blockOpen(b)
	for _, s := range b.Stmts {
		f.emitStmt(s)
	}
	if tail != nil {
		tail()
	}
	f.blockClose()
	f.hoist = savedHoist
}

// collectGotos gathers the labels targeted by goto in a function body,
// without descending into nested function literals.
func collectGotos(b *ast.Block) map[string]bool {
	labels := map[string]bool{}
	var walk func(stmts []ast.Stmt)
	walk = func(stmts []ast.Stmt) {
		for _, s := range stmts {
			switch v := s.(type) {
			case *ast.GotoStmt:
				labels[v.Label] = true
			case *ast.DoStmt:
				walk(v.Body.Stmts)
			case *ast.WhileStmt:
				walk(v.Body.Stmts)
			case *ast.RepeatStmt:
				walk(v.Body.Stmts)
			case *ast.IfStmt:
				for _, blk := range v.Blocks {
					walk(blk.Stmts)
				}
				if v.Else != nil {
					walk(v.Else.Stmts)
				}
			case *ast.NumForStmt:
				walk(v.Body.Stmts)
			case *ast.GenForStmt:
				walk(v.Body.Stmts)
			}
		}
	}
	walk(b.Stmts)
	return labels
}

// ---------------------------------------------------------------------------
// Statements
// ---------------------------------------------------------------------------

func (f *fnGen) emitStmt(s ast.Stmt) {
	f.pendingLabel = false
	switch v := s.(type) {
	case *ast.LocalStmt:
		f.emitLocal(v)
	case *ast.AssignStmt:
		f.emitAssign(v)
	case *ast.CallStmt:
		f.emitCallStmt(v)
	case *ast.DoStmt:
		f.line("{")
		f.ind++
		f.emitBlock(v.Body)
		f.ind--
		f.line("}")
	case *ast.WhileStmt:
		f.emitWhile(v)
	case *ast.RepeatStmt:
		f.emitRepeat(v)
	case *ast.IfStmt:
		f.emitIf(v)
	case *ast.NumForStmt:
		f.emitNumFor(v)
	case *ast.GenForStmt:
		f.emitGenFor(v)
	case *ast.FuncStmt:
		f.emitFuncStat(v)
	case *ast.LocalFuncStmt:
		f.emitLocalFunc(v)
	case *ast.ReturnStmt:
		if f.g.collecting && f.fnGN != "" {
			ok := len(v.Vals) == 1 && f.isNumExpr(v.Vals[0])
			if !f.g.fnRetSeen[f.fnGN] {
				f.g.fnRetNum[f.fnGN] = ok
			} else {
				f.g.fnRetNum[f.fnGN] = f.g.fnRetNum[f.fnGN] && ok
			}
			f.g.fnRetSeen[f.fnGN] = true
		}
		if f.numFn {
			f.line("return %s", f.numSrc(v.Vals[0]))
			return
		}
		if f.direct {
			// Direct functions were qualified to return exactly one value.
			f.line("return %s", f.expr(v.Vals[0]))
			return
		}
		f.line("return %s", f.listExpr(v.Vals))
	case *ast.BreakStmt:
		f.line("break")
	case *ast.GotoStmt:
		f.line("goto %s", f.labelGoName(v.Label))
	case *ast.LabelStmt:
		if !f.labels[v.Name] {
			return // untargeted labels have no runtime effect
		}
		f.line("%s:", f.labelGoName(v.Name))
		f.pendingLabel = true
	default:
		panic(fmt.Sprintf("codegen: unknown statement %T", s))
	}
}

func (f *fnGen) emitLocal(v *ast.LocalStmt) {
	if hoisted, ok := f.hoist[v]; ok {
		vals := f.evalExplist(v.Vals, len(v.Names))
		for i, gn := range hoisted {
			f.g.markNoNum(gn) // hoisted declarations stay lg.Value
			f.g.bind(v.Names[i], gn)
			f.g.recordAssign(gn, false)
		}
		for i, gn := range hoisted {
			f.line("%s = %s", gn, vals[i])
		}
		return
	}
	valAt := f.adjustedExprs(v.Vals, len(v.Names))
	gns := make([]string, len(v.Names))
	for i, name := range v.Names {
		gns[i] = f.g.declare(name)
	}
	// Record the assignment facts first: the inferred types drive the
	// emission below, and both passes use the same Go names.
	for i, gn := range gns {
		if len(v.Vals) > 0 {
			f.g.markDeclInit(gn)
		}
		f.curLocal = gn
		num := valAt[i] != nil && f.isNumExpr(valAt[i])
		f.curLocal = ""
		f.g.recordAssign(gn, num)
	}
	// A multi-value initializer is materialized once and adjusted.
	if n := len(v.Vals); n > 0 && isMulti(v.Vals[n-1]) && !f.isDirectCall(v.Vals[n-1]) {
		vals := f.evalExplist(v.Vals, len(v.Names))
		for i, gn := range gns {
			f.line("var %s lg.Value = %s", gn, vals[i])
			f.line("_ = %s", gn)
		}
		return
	}
	for i, gn := range gns {
		switch {
		case valAt[i] == nil:
			f.line("var %s lg.Value = lg.Nil", gn)
		case f.g.isNumLocal(gn):
			f.line("var %s float64 = %s", gn, f.numSrc(valAt[i]))
		default:
			f.line("var %s lg.Value = %s", gn, f.expr(valAt[i]))
		}
		f.line("_ = %s", gn)
	}
}

func (f *fnGen) emitAssign(v *ast.AssignStmt) {
	valAt := f.adjustedExprs(v.Vals, len(v.Targets))
	for i, t := range v.Targets {
		if nm, ok := t.(*ast.NameExpr); ok {
			if gn, ok2 := f.g.resolve(nm.Name); ok2 {
				f.curLocal = gn
				num := valAt[i] != nil && f.isNumExpr(valAt[i])
				f.curLocal = ""
				f.g.recordAssign(gn, num)
			}
		}
	}
	// Numeric fast path: every target is a float64 local, so each value is
	// computed natively and stored directly.
	allNum := true
	for i, t := range v.Targets {
		nm, ok := t.(*ast.NameExpr)
		if !ok || valAt[i] == nil {
			allNum = false
			break
		}
		gn, ok := f.g.resolve(nm.Name)
		if !ok || !f.g.isNumLocal(gn) {
			allNum = false
			break
		}
	}
	if allNum {
		// Values are materialized before the stores: numeric swap must not
		// observe a half-updated set of targets.
		tmps := make([]string, len(v.Targets))
		for i := range v.Targets {
			tmps[i] = f.temp("n")
			f.line("%s := %s", tmps[i], f.numSrc(valAt[i]))
		}
		for i, t := range v.Targets {
			gn, _ := f.g.resolve(t.(*ast.NameExpr).Name)
			f.line("%s = %s", gn, tmps[i])
		}
		return
	}
	// Fast path: one target, one value.
	if len(v.Targets) == 1 && len(v.Vals) == 1 {
		switch lv := v.Vals[0].(type) {
		case *ast.CallExpr:
			callee, isCall := f.recordCall(lv)
			if src, ok := f.directCallSrc(lv); ok {
				f.assignTo(v.Targets[0], src)
				return
			}
			fn := callee
			if !isCall {
				fn = f.expr(lv.Fn)
			}
			args := f.callArgs(lv.Args, "")
			f.assignTo(v.Targets[0], fmt.Sprintf("lg.Call1(env, %s, %s)", fn, args))
			return
		case *ast.MethodExpr:
			recv := f.temp("recv")
			f.line("%s := %s", recv, f.expr(lv.Obj))
			args := f.callArgs(lv.Args, recv)
			f.assignTo(v.Targets[0], fmt.Sprintf("lg.Call1(env, lg.Index(env, %s, lg.String(%s)), %s)",
				recv, strconv.Quote(lv.Name), args))
			return
		case *ast.VarargExpr:
			f.assignTo(v.Targets[0], fmt.Sprintf("lg.Pick(%s, 0)", f.va))
			return
		default:
			f.assignTo(v.Targets[0], f.expr(v.Vals[0]))
			return
		}
	}
	// Lua evaluates every target's object and key expression before it stores
	// anything, and before the right-hand side runs. `i, t[i] = 2, 99` must
	// therefore write t[1], not t[2].
	type indexTemps struct{ obj, key string }
	pre := make([]indexTemps, len(v.Targets))
	for i, t := range v.Targets {
		ix, ok := t.(*ast.IndexExpr)
		if !ok {
			continue
		}
		obj := f.temp("obj")
		f.line("%s := %s", obj, f.expr(ix.Obj))
		key := f.temp("key")
		f.line("%s := %s", key, f.expr(ix.Key))
		pre[i] = indexTemps{obj: obj, key: key}
	}
	// Materialize the RHS once: each target picks from the same value list
	// (t[i], t[j] = t[j], t[i] must swap, not evaluate twice).
	r := f.temp("r")
	f.line("%s := %s", r, f.listExpr(v.Vals))
	for i, t := range v.Targets {
		if pre[i].obj != "" {
			f.line("lg.SetIndex(env, %s, %s, lg.Pick(%s, %d))", pre[i].obj, pre[i].key, r, i)
			continue
		}
		if nm, ok := t.(*ast.NameExpr); ok {
			if gn, ok2 := f.g.resolve(nm.Name); ok2 && f.g.isNumLocal(gn) {
				f.line("%s = lg.NumVal(lg.Pick(%s, %d))", gn, r, i)
				continue
			}
		}
		f.assignTo(t, fmt.Sprintf("lg.Pick(%s, %d)", r, i))
	}
}

// assignTo emits an assignment to a name or index target.
func (f *fnGen) assignTo(target ast.Expr, val string) {
	switch t := target.(type) {
	case *ast.NameExpr:
		if gn, ok := f.g.resolve(t.Name); ok {
			if f.g.collecting {
				f.g.usageFor(gn).other++
			}
			f.line("%s = %s", gn, val)
			return
		}
		f.line("env.Set(%s, %s)", strconv.Quote(t.Name), val)
	case *ast.IndexExpr:
		f.line("lg.SetIndex(env, %s, %s, %s)", f.expr(t.Obj), f.expr(t.Key), val)
	default:
		panic(fmt.Sprintf("codegen: invalid assignment target %T", target))
	}
}

// recordCall notes a call site of a local function during pass 1. A call
// whose callee is a local name is only eligible for direct-call
// specialization when it is not in a multi-value position.
// It returns the callee's Go name so the call site can emit it directly
// instead of routing the name through expr(), which would count it as a
// value reference.
func (f *fnGen) recordCall(c *ast.CallExpr) (string, bool) {
	if !f.g.collecting {
		return "", false
	}
	nm, ok := c.Fn.(*ast.NameExpr)
	if !ok {
		return "", false
	}
	gn, ok := f.g.resolve(nm.Name)
	if !ok {
		return "", false
	}
	u := f.g.usageFor(gn)
	u.calls++
	u.arities = append(u.arities, len(c.Args))
	if len(c.Args) > 0 && isMulti(c.Args[len(c.Args)-1]) {
		u.multiLast = true
	}
	f.recordCallArgs(gn, c.Args)
	return gn, true
}

// recordCallArgs notes whether every argument of a call site is a numeric
// expression, which decides whether the callee can take float64 parameters.
func (f *fnGen) recordCallArgs(gn string, args []ast.Expr) {
	if !f.g.collecting {
		return
	}
	all := true
	for _, a := range args {
		if !f.isNumExpr(a) {
			all = false
			break
		}
	}
	if cur, seen := f.g.fnParamNum[gn]; seen {
		f.g.fnParamNum[gn] = cur && all
	} else {
		f.g.fnParamNum[gn] = all
	}
}

func (f *fnGen) emitCallStmt(v *ast.CallStmt) {
	switch c := v.Call.(type) {
	case *ast.CallExpr:
		callee, isCall := f.recordCall(c)
		if src, ok := f.directCallSrc(c); ok {
			f.line("_ = %s", src)
			return
		}
		fn := callee
		if !isCall {
			fn = f.expr(c.Fn)
		}
		args := f.callArgs(c.Args, "")
		f.line("lg.Call(env, %s, %s)", fn, args)
	case *ast.MethodExpr:
		recv := f.temp("recv")
		f.line("%s := %s", recv, f.expr(c.Obj))
		args := f.callArgs(c.Args, recv)
		f.line("lg.Call(env, lg.Index(env, %s, lg.String(%s)), %s)", recv, strconv.Quote(c.Name), args)
	default:
		panic(fmt.Sprintf("codegen: invalid call statement %T", v.Call))
	}
}

func (f *fnGen) emitWhile(v *ast.WhileStmt) {
	f.line("for {")
	f.ind++
	// The condition is re-evaluated inside the loop, so any temporaries it
	// needs are re-created every iteration.
	if b, ok := v.Cond.(*ast.BoolExpr); !ok || !b.Val {
		c := f.cond(v.Cond)
		f.line("if !%s { break }", c)
	}
	f.emitBlock(v.Body)
	f.ind--
	f.line("}")
}

func (f *fnGen) emitRepeat(v *ast.RepeatStmt) {
	f.line("for {")
	f.ind++
	f.emitBlockWithTail(v.Body, func() {
		// The until condition sees the body's locals (Lua semantics), so it
		// is emitted inside the body scope.
		c := f.cond(v.Cond)
		f.line("if %s { break }", c)
	})
	f.ind--
	f.line("}")
}

func (f *fnGen) emitIf(v *ast.IfStmt) {
	c := f.cond(v.Conds[0])
	f.line("if %s {", c)
	f.ind++
	f.emitBlock(v.Blocks[0])
	f.ind--
	if len(v.Conds) > 1 {
		f.line("} else {")
		f.ind++
		f.emitIf(&ast.IfStmt{Conds: v.Conds[1:], Blocks: v.Blocks[1:], Else: v.Else})
		f.ind--
		f.line("}")
	} else if v.Else != nil {
		f.line("} else {")
		f.ind++
		f.emitBlock(v.Else)
		f.ind--
		f.line("}")
	} else {
		f.line("}")
	}
}

func (f *fnGen) emitNumFor(v *ast.NumForStmt) {
	init := f.expr(v.Init)
	limit := f.expr(v.Limit)
	step := "lg.Number(1)"
	if v.Step != nil {
		step = f.expr(v.Step)
	}
	nf := f.temp("nf")
	f.line("%s := lg.NewNumFor(%s, %s, %s)", nf, init, limit, step)
	f.line("for {")
	f.ind++
	f.g.pushScope()
	iv := f.g.declare(v.Var)
	f.g.markLoopVar(iv)
	okv := f.temp("ok")
	if f.g.isNumLocal(iv) {
		f.line("%s, %s := %s.NextNum()", iv, okv, nf)
	} else {
		f.line("%s, %s := %s.Next()", iv, okv, nf)
		f.line("_ = %s", iv)
	}
	f.line("if !%s { break }", okv)
	f.emitBlock(v.Body)
	f.g.popScope()
	f.ind--
	f.line("}")
}

func (f *fnGen) emitGenFor(v *ast.GenForStmt) {
	vals := f.evalExplist(v.Exprs, 3)
	gf := f.temp("gf")
	f.line("%s := lg.NewGenFor(env, %s, %s, %s)", gf, vals[0], vals[1], vals[2])
	f.line("for {")
	f.ind++
	f.g.pushScope()
	rs := f.temp("rs")
	f.line("%s := %s.Next()", rs, gf)
	f.line("if %s == nil { break }", rs)
	for i, name := range v.Names {
		nv := f.g.declare(name)
		f.line("%s := lg.Pick(%s, %d)", nv, rs, i)
		f.line("_ = %s", nv)
	}
	f.emitBlock(v.Body)
	f.g.popScope()
	f.ind--
	f.line("}")
}

func (f *fnGen) emitFuncStat(v *ast.FuncStmt) {
	name := v.Method
	if name == "" {
		if n, ok := v.Target.(*ast.NameExpr); ok {
			name = n.Name
		}
	}
	closure := f.g.closure(v.Params, v.Vararg, name, v.Body)
	switch t := v.Target.(type) {
	case *ast.NameExpr:
		if v.Method == "" {
			if gn, ok := f.g.resolve(t.Name); ok {
				f.line("%s = %s", gn, closure)
			} else {
				f.line("env.Set(%s, %s)", strconv.Quote(t.Name), closure)
			}
			return
		}
		// function name:method() -> name.method = closure
		var obj string
		if gn, ok := f.g.resolve(t.Name); ok {
			obj = gn
		} else {
			obj = fmt.Sprintf("env.Get(%s)", strconv.Quote(t.Name))
		}
		f.line("lg.SetIndex(env, %s, lg.String(%s), %s)", obj, strconv.Quote(v.Method), closure)
	case *ast.IndexExpr:
		f.line("lg.SetIndex(env, %s, %s, %s)", f.expr(t.Obj), f.expr(t.Key), closure)
	default:
		panic(fmt.Sprintf("codegen: bad function target %T", v.Target))
	}
}

func (f *fnGen) emitLocalFunc(v *ast.LocalFuncStmt) {
	if hoisted, ok := f.hoist[v]; ok {
		gn := hoisted[0]
		f.g.bind(v.Name, gn) // visible inside its own body for recursion
		closure := f.g.closure(v.Params, v.Vararg, v.Name, v.Body)
		f.line("%s = %s", gn, closure)
		return
	}
	gn := f.g.reserve(v.Name) // same numbering as pass 1's declare
	if f.g.collecting {
		f.g.localFuncs[gn] = v
	}
	// Direct-call specialization: emit a fixed-arity Go func when the
	// function is only ever called directly (decided in pass 1).
	if di, ok := f.g.direct[gn]; ok {
		f.g.declareDirect(v.Name, di)
		ptype, rtype := "lg.Value", "lg.Value"
		if f.g.numFunc(gn) {
			ptype, rtype = "float64", "float64"
		}
		types := strings.TrimSuffix(strings.Repeat(ptype+", ", len(v.Params)), ", ")
		if types != "" {
			types = ", " + types
		}
		f.line("var %s func(*lg.Env%s) %s", gn, types, rtype)
		f.line("%s = %s", gn, f.g.directFuncSrc(gn, v.Params, v.Body))
		return
	}
	f.g.bind(v.Name, gn)
	// Declare first, assign second: in Go the scope of a variable starts
	// after its declaration statement, so the closure literal (which
	// references the name for recursion) cannot appear in the initializer.
	closure := f.g.closure(v.Params, v.Vararg, v.Name, v.Body)
	f.line("var %s lg.Value", gn)
	f.line("_ = %s", gn)
	f.line("%s = %s", gn, closure)
}

// directFuncSrc emits a fixed-arity Go func literal for a Lua local
// function that is only ever called directly.
func (g *gen) directFuncSrc(gn string, params []string, body *ast.Block) string {
	typed := g.numFunc(gn)
	ptype := "lg.Value"
	if typed {
		ptype = "float64"
	}
	f := &fnGen{g: g, direct: !typed, numFn: typed, fnGN: gn, labelGo: map[string]string{}, labels: collectGotos(body)}
	g.pushScope()
	pns := make([]string, len(params))
	for i, p := range params {
		pns[i] = g.declare(p)
	}
	if g.collecting {
		g.fnParams[gn] = pns
	}
	sig := "func(env *lg.Env"
	for _, pn := range pns {
		sig += ", " + pn + " " + ptype
	}
	if typed {
		sig += ") float64 {"
	} else {
		sig += ") lg.Value {"
	}
	f.ind = 1
	f.emitBlock(body)
	if !endsWithReturn(body) {
		if typed {
			f.line("return 0")
		} else {
			f.line("return lg.Nil")
		}
	}
	g.popScope()
	return sig + "\n" + strings.Join(f.buf, "\n") + "\n}"
}

// calleeSrc emits a call's callee expression, recording a local callee as a
// call reference (pass 1) rather than as a value reference.
func (f *fnGen) calleeSrc(c *ast.CallExpr) string {
	if gn, ok := f.recordCall(c); ok {
		return gn
	}
	return f.expr(c.Fn)
}

// directCallSrc returns the Go source for a direct call to a specialized
// local function, or ok=false when the call is not one.
func (f *fnGen) directCallSrc(c *ast.CallExpr) (string, bool) {
	src, typed, ok := f.directCallNum(c)
	if !ok {
		return "", false
	}
	if typed {
		return "lg.Number(" + src + ")", true
	}
	return src, true
}

// directCallNum builds the raw Go call for a specialized local function and
// reports whether the callee is emitted with a float64 signature.
func (f *fnGen) directCallNum(c *ast.CallExpr) (src string, typed, ok bool) {
	nm, ok := c.Fn.(*ast.NameExpr)
	if !ok {
		return "", false, false
	}
	di, ok := f.g.resolveDirect(nm.Name)
	if !ok || len(c.Args) != di.arity {
		return "", false, false
	}
	f.recordCallArgs(di.goName, c.Args)
	typed = f.g.numFunc(di.goName)
	var sb strings.Builder
	sb.WriteString(di.goName)
	sb.WriteString("(env")
	for _, a := range c.Args {
		sb.WriteString(", ")
		if typed {
			sb.WriteString(f.numSrc(a))
		} else {
			sb.WriteString(f.expr(a))
		}
	}
	sb.WriteString(")")
	return sb.String(), typed, true
}

// isDirectCall reports whether e is a call that will be emitted as a
// direct Go call (such calls always produce exactly one value).
func (f *fnGen) isDirectCall(e ast.Expr) bool {
	c, ok := e.(*ast.CallExpr)
	if !ok {
		return false
	}
	nm, ok := c.Fn.(*ast.NameExpr)
	if !ok {
		return false
	}
	di, ok := f.g.resolveDirect(nm.Name)
	return ok && len(c.Args) == di.arity
}


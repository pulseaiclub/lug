// isMulti reports whether e may produce multiple values.
func isMulti(e ast.Expr) bool {
	switch e.(type) {
	case *ast.CallExpr, *ast.MethodExpr, *ast.VarargExpr:
		return true
	}
	return false
}

func (f *fnGen) expr(e ast.Expr) string {
	switch v := e.(type) {
	case *ast.NilExpr:
		return "lg.Nil"
	case *ast.BoolExpr:
		if v.Val {
			return "lg.True"
		}
		return "lg.False"
	case *ast.NumberExpr:
		return fmt.Sprintf("lg.Number(%s)", strconv.FormatFloat(v.Val, 'g', -1, 64))
	case *ast.StringExpr:
		return "lg.String(" + strconv.Quote(v.Val) + ")"
	case *ast.VarargExpr:
		return fmt.Sprintf("lg.Pick(%s, 0)", f.va)
	case *ast.NameExpr:
		if gn, ok := f.g.resolve(v.Name); ok {
			if f.g.collecting {
				f.g.usageFor(gn).other++
			}
			if f.g.isNumLocal(gn) {
				return "lg.Number(" + gn + ")"
			}
			return gn
		}
		return fmt.Sprintf("env.Get(%s)", strconv.Quote(v.Name))
	case *ast.ParenExpr:
		// (f()) truncates to one value; expr() on a call already yields
		// exactly one value via lg.Call1.
		return f.expr(v.X)
	case *ast.IndexExpr:
		return fmt.Sprintf("lg.Index(env, %s, %s)", f.expr(v.Obj), f.expr(v.Key))
	case *ast.CallExpr:
		callee, isCall := f.recordCall(v)
		if src, ok := f.directCallSrc(v); ok {
			return src
		}
		fn := callee
		if !isCall {
			fn = f.expr(v.Fn)
		}
		args := f.callArgs(v.Args, "")
		return fmt.Sprintf("lg.Call1(env, %s, %s)", fn, args)
	case *ast.MethodExpr:
		recv := f.temp("recv")
		f.line("%s := %s", recv, f.expr(v.Obj))
		args := f.callArgs(v.Args, recv)
		return fmt.Sprintf("lg.Call1(env, lg.Index(env, %s, lg.String(%s)), %s)",
			recv, strconv.Quote(v.Name), args)
	case *ast.FuncExpr:
		return f.g.closure(v.Params, v.Vararg, "", v.Body)
	case *ast.TableExpr:
		return f.tableExpr(v)
	case *ast.BinExpr:
		return f.binExpr(v)
	case *ast.UnExpr:
		return f.unExpr(v)
	}
	panic(fmt.Sprintf("codegen: unknown expression %T", e))
}

// floatLit renders a float64 literal that Go treats as a float, so that
// constant folding never falls back to integer arithmetic.
func floatLit(f float64) string {
	s := strconv.FormatFloat(f, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

// exprNum returns a Go float64 expression for e when e is statically known
// to be a number. It never emits statements.
func (f *fnGen) exprNum(e ast.Expr) (string, bool) {
	switch v := e.(type) {
	case *ast.NumberExpr:
		return "(" + floatLit(v.Val) + ")", true
	case *ast.UnExpr:
		if v.Op == ast.UnNeg {
			if x, ok := f.exprNum(v.X); ok {
				return "(-" + x + ")", true
			}
		}
	case *ast.BinExpr:
		l, ok1 := f.exprNum(v.L)
		if !ok1 {
			return "", false
		}
		r, ok2 := f.exprNum(v.R)
		if !ok2 {
			return "", false
		}
		switch v.Op {
		case ast.OpAdd:
			return "(" + l + " + " + r + ")", true
		case ast.OpSub:
			return "(" + l + " - " + r + ")", true
		case ast.OpMul:
			return "(" + l + " * " + r + ")", true
		case ast.OpDiv:
			return "(" + l + " / " + r + ")", true
		case ast.OpMod:
			return "lg.ModNum(" + l + ", " + r + ")", true
		case ast.OpPow:
			return "lg.PowNum(" + l + ", " + r + ")", true
		case ast.OpIDiv:
			return "lg.IDivNum(" + l + ", " + r + ")", true
		}
	case *ast.NameExpr:
		if gn, ok := f.g.resolve(v.Name); ok && f.g.isNumLocal(gn) {
			return gn, true
		}
	case *ast.CallExpr:
		if src, typed, ok := f.directCallNum(v); ok && typed {
			return src, true
		}
	}
	return "", false
}

// numSrc returns a Go float64 expression for e, falling back to a runtime
// conversion when the static inference is inconclusive.
func (f *fnGen) numSrc(e ast.Expr) string {
	if src, ok := f.exprNum(e); ok {
		return src
	}
	return "lg.NumVal(" + f.expr(e) + ")"
}

// numExprSrc returns the numeric source of e when e is inferred numeric,
// used by the arithmetic and comparison fast paths.
func (f *fnGen) numPair(l, r ast.Expr) (string, string, bool) {
	ls, ok1 := f.exprNum(l)
	if !ok1 {
		return "", "", false
	}
	rs, ok2 := f.exprNum(r)
	if !ok2 {
		return "", "", false
	}
	return ls, rs, true
}

// numCompare renders a Go comparison of two float64 expressions.
func numCompare(op ast.BinOp, l, r string) (string, bool) {
	switch op {
	case ast.OpLT:
		return "(" + l + " < " + r + ")", true
	case ast.OpGT:
		return "(" + l + " > " + r + ")", true
	case ast.OpLE:
		return "(" + l + " <= " + r + ")", true
	case ast.OpGE:
		return "(" + l + " >= " + r + ")", true
	case ast.OpEQ:
		return "(" + l + " == " + r + ")", true
	case ast.OpNE:
		return "(" + l + " != " + r + ")", true
	}
	return "", false
}

// cond emits a Go bool expression for a Lua condition, using the direct
// comparison helpers when possible.
func (f *fnGen) cond(e ast.Expr) string {
	if b, ok := e.(*ast.BinExpr); ok {
		if ls, rs, ok := f.numPair(b.L, b.R); ok {
			if src, ok := numCompare(b.Op, ls, rs); ok {
				return src
			}
		}
		switch b.Op {
		case ast.OpLT:
			return fmt.Sprintf("lg.LT(env, %s, %s)", f.expr(b.L), f.expr(b.R))
		case ast.OpGT:
			return fmt.Sprintf("lg.LT(env, %s, %s)", f.expr(b.R), f.expr(b.L))
		case ast.OpLE:
			return fmt.Sprintf("lg.LE(env, %s, %s)", f.expr(b.L), f.expr(b.R))
		case ast.OpGE:
			return fmt.Sprintf("lg.LE(env, %s, %s)", f.expr(b.R), f.expr(b.L))
		case ast.OpEQ:
			return fmt.Sprintf("lg.EQ(env, %s, %s)", f.expr(b.L), f.expr(b.R))
		case ast.OpNE:
			return fmt.Sprintf("!lg.EQ(env, %s, %s)", f.expr(b.L), f.expr(b.R))
		}
	}
	if u, ok := e.(*ast.UnExpr); ok && u.Op == ast.UnNot {
		return "!lg.Truth(" + f.expr(u.X) + ")"
	}
	return "lg.Truth(" + f.expr(e) + ")"
}

func (f *fnGen) tableExpr(t *ast.TableExpr) string {
	tv := f.temp("t")
	f.line("%s := lg.NewTable()", tv)
	n := 0
	for i, fld := range t.Fields {
		if fld.Key != nil {
			f.line("%s.Set(%s, %s)", tv, f.expr(fld.Key), f.expr(fld.Val))
			continue
		}
		n++
		if isMulti(fld.Val) && i == len(t.Fields)-1 {
			switch lv := fld.Val.(type) {
			case *ast.CallExpr:
				fn := f.expr(lv.Fn)
				args := f.callArgs(lv.Args, "")
				f.line("lg.ExtendArray(%s, lg.Call(env, %s, %s), %d)", tv, fn, args, n)
			case *ast.MethodExpr:
				recv := f.temp("recv")
				f.line("%s := %s", recv, f.expr(lv.Obj))
				args := f.callArgs(lv.Args, recv)
				f.line("lg.ExtendArray(%s, lg.Call(env, lg.Index(env, %s, lg.String(%s)), %s), %d)",
					tv, recv, strconv.Quote(lv.Name), args, n)
			case *ast.VarargExpr:
				f.line("lg.ExtendArray(%s, %s, %d)", tv, f.va, n)
			}
			continue
		}
		f.line("%s.Set(lg.Number(%d), %s)", tv, n, f.expr(fld.Val))
	}
	return "lg.TableVal(" + tv + ")"
}

func (f *fnGen) binExpr(b *ast.BinExpr) string {
	switch b.Op {
	case ast.OpAnd:
		tmp := f.temp("b")
		f.line("%s := %s", tmp, f.expr(b.L))
		f.line("if lg.Truth(%s) {", tmp)
		f.ind++
		f.line("%s = %s", tmp, f.expr(b.R))
		f.ind--
		f.line("}")
		return tmp
	case ast.OpOr:
		tmp := f.temp("b")
		f.line("%s := %s", tmp, f.expr(b.L))
		f.line("if !lg.Truth(%s) {", tmp)
		f.ind++
		f.line("%s = %s", tmp, f.expr(b.R))
		f.ind--
		f.line("}")
		return tmp
	case ast.OpLT, ast.OpGT, ast.OpLE, ast.OpGE, ast.OpEQ, ast.OpNE:
		if ls, rs, ok := f.numPair(b.L, b.R); ok {
			if src, ok := numCompare(b.Op, ls, rs); ok {
				return "lg.Bool(" + src + ")"
			}
		}
		switch b.Op {
		case ast.OpLT:
			return fmt.Sprintf("lg.Bool(lg.LT(env, %s, %s))", f.expr(b.L), f.expr(b.R))
		case ast.OpGT:
			return fmt.Sprintf("lg.Bool(lg.LT(env, %s, %s))", f.expr(b.R), f.expr(b.L))
		case ast.OpLE:
			return fmt.Sprintf("lg.Bool(lg.LE(env, %s, %s))", f.expr(b.L), f.expr(b.R))
		case ast.OpGE:
			return fmt.Sprintf("lg.Bool(lg.LE(env, %s, %s))", f.expr(b.R), f.expr(b.L))
		case ast.OpEQ:
			return fmt.Sprintf("lg.Bool(lg.EQ(env, %s, %s))", f.expr(b.L), f.expr(b.R))
		case ast.OpNE:
			return fmt.Sprintf("lg.Bool(!lg.EQ(env, %s, %s))", f.expr(b.L), f.expr(b.R))
		}
	}
	// Numeric fast path: both operands are float64 locals, so the operation
	// compiles to native Go arithmetic.
	switch b.Op {
	case ast.OpAdd, ast.OpSub, ast.OpMul, ast.OpDiv, ast.OpMod, ast.OpPow, ast.OpIDiv:
		if src, ok := f.exprNum(b); ok {
			return "lg.Number(" + src + ")"
		}
	}
	var fn string
	switch b.Op {
	case ast.OpConcat:
		fn = "lg.Concat"
	case ast.OpAdd:
		fn = "lg.Add"
	case ast.OpSub:
		fn = "lg.Sub"
	case ast.OpMul:
		fn = "lg.Mul"
	case ast.OpDiv:
		fn = "lg.Div"
	case ast.OpIDiv:
		fn = "lg.IDiv"
	case ast.OpMod:
		fn = "lg.Mod"
	case ast.OpPow:
		fn = "lg.Pow"
	case ast.OpBor:
		fn = "lg.BitOr"
	case ast.OpBxor:
		fn = "lg.BitXor"
	case ast.OpBand:
		fn = "lg.BitAnd"
	case ast.OpShl:
		fn = "lg.Shl"
	case ast.OpShr:
		fn = "lg.Shr"
	default:
		panic(fmt.Sprintf("codegen: unknown binary op %v", b.Op))
	}
	return fmt.Sprintf("%s(env, %s, %s)", fn, f.expr(b.L), f.expr(b.R))
}

func (f *fnGen) unExpr(u *ast.UnExpr) string {
	switch u.Op {
	case ast.UnNeg:
		if num, ok := u.X.(*ast.NumberExpr); ok {
			return fmt.Sprintf("lg.Number(%s)", strconv.FormatFloat(-num.Val, 'g', -1, 64))
		}
		return fmt.Sprintf("lg.Unm(env, %s)", f.expr(u.X))
	case ast.UnNot:
		return fmt.Sprintf("lg.Bool(!lg.Truth(%s))", f.expr(u.X))
	case ast.UnLen:
		return fmt.Sprintf("lg.Len(env, %s)", f.expr(u.X))
	case ast.UnBnot:
		return fmt.Sprintf("lg.BitNot(env, %s)", f.expr(u.X))
	}
	panic(fmt.Sprintf("codegen: unknown unary op %v", u.Op))
}

